import {chromium,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const url=process.env.CVG_UI_URL||'http://127.0.0.1:5175';
try{
 await page.goto(url);
 await page.getByRole('button',{name:/Case 3:/}).click();
 await expect(page.getByRole('heading',{name:'Your research report.'})).toBeVisible({timeout:120000});
 await expect(page.getByText('Atrial fibrillation rhythm model',{exact:true})).toBeVisible();
 await expect(page.getByText(/Processed signal overview/)).toBeVisible();
 await page.getByText('Explore a lifestyle scenario',{exact:true}).click();
 await page.getByLabel('Systolic BP · mmHg').fill('125');
 await page.getByRole('button',{name:'Simulate changes'}).click();
 await expect(page.getByText(/Composite burden index change:/)).toBeVisible({timeout:30000});
 await page.getByRole('button',{name:'Edit inputs',exact:true}).click();
 await page.getByRole('tab',{name:'Enter details'}).click();
 await page.getByLabel('Age',{exact:false}).first().fill('45');
 await page.getByRole('button',{name:'Review inputs',exact:true}).click();
 await page.getByRole('button',{name:'Generate research report'}).click();
 await expect(page.getByRole('heading',{name:'Your research report.'})).toBeVisible({timeout:120000});
 await page.getByRole('button',{name:'Edit inputs',exact:true}).click();
 await page.getByLabel('Select laboratory report').setInputFiles('public/demo_files/sample_lipid_hba1c_report.pdf');
 await expect(page.getByText(/values extracted by the API/)).toBeVisible({timeout:30000});
 await expect(page.getByText(/Extraction evidence/)).toBeVisible();
 await page.getByRole('button',{name:'Review inputs',exact:true}).click();
 await page.getByRole('button',{name:'Generate research report'}).click();
 await expect(page.getByRole('heading',{name:'Your research report.'})).toBeVisible({timeout:120000});
 await page.pdf({path:'qa/connected-report.pdf',format:'A4'});
 await page.screenshot({path:'qa/connected-report.png',fullPage:true});
 const axe=await new AxeBuilder({page}).analyze();
 console.log('Accessibility violations:',JSON.stringify(axe.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}))));
 expect(axe.violations).toEqual([]);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBeTruthy();
 expect(errors).toEqual([]);
 console.log('PASS: live demo, digital prediction, edits, PDF extraction, evidence, simulation, printing, mobile, no runtime errors');
}finally{await browser.close();}
