import {chromium,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const requests=[],errors=[],checks=[];
page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:5174/')||r.url().includes('/api/'))requests.push(r.url());});
page.on('pageerror',e=>errors.push(e.message));
const pass=s=>{checks.push(s);console.log('PASS '+s)};
try{
 await page.goto('http://127.0.0.1:5174');
 await page.getByRole('button',{name:'Try a sample',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.keyboard.press('Escape');
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await expect(page.getByRole('button',{name:'Try a sample',exact:true})).toBeFocused();
 pass('Dialog keyboard dismissal restores focus');
 await page.getByRole('button',{name:'Try a sample',exact:true}).click();
 await page.getByRole('button',{name:'Explore sample',exact:true}).click();
 await expect(page.locator('#review-age')).toHaveValue('46');
 await expect(page.locator('#review-sex')).toHaveValue('female');
 await page.getByRole('button',{name:'View sample report',exact:true}).click();
 await expect(page.getByText('94.3',{exact:false}).first()).toBeVisible();
 await expect(page.locator('.rpt-metric').nth(2)).toContainText('1.273');
 await expect(page.getByText('Inconclusive',{exact:true})).toHaveCount(2);
 await expect(page.locator('h1')).toHaveCount(1);
 pass('Recorded sample outputs match fixture and preserve abstentions');
 await page.getByRole('tab',{name:'Overview',exact:true}).focus();
 await page.keyboard.press('ArrowRight');
 await expect(page.getByRole('tab',{name:'ECG explorer',exact:true})).toBeFocused();
 await expect(page.getByText('No waveform to display',{exact:true})).toBeVisible();
 await page.keyboard.press('ArrowRight');
 await expect(page.getByRole('tab',{name:'Explore scenarios',exact:true})).toBeFocused();
 await page.locator('#scenario-systolic_bp').fill('126');
 await expect(page.locator('.rpt-scenario-comparison tbody tr').first()).toContainText('116');
 await expect(page.locator('.rpt-scenario-comparison tbody tr').first()).toContainText('126');
 await page.getByRole('button',{name:'Reset',exact:true}).click();
 await expect(page.locator('#scenario-systolic_bp')).toHaveValue('116');
 await page.locator('#scenario-systolic_bp').fill('999');
 await expect(page.locator('#scenario-systolic_bp')).toHaveAttribute('aria-invalid','true');
 await page.getByRole('button',{name:'Reset',exact:true}).click();
 pass('Scenario controls compare inputs, validate, reset, and preserve baseline');
 await page.getByRole('tab',{name:'Overview',exact:true}).click();
 await mkdir('qa/screenshots',{recursive:true});
 await page.screenshot({path:'qa/screenshots/report-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'qa/screenshots/report-mobile.png',fullPage:true});
 await page.pdf({path:'qa/sample-report.pdf',format:'A4',printBackground:true});
 pass('Report fits 390px and printable PDF is generated');
 await page.getByRole('button',{name:'Edit inputs',exact:true}).click();
 await page.getByRole('tab',{name:'Enter details',exact:true}).click();
 await page.locator('#inp-age').fill('47');
 await page.locator('.inp-footer button').click();
 await page.getByRole('button',{name:'View report',exact:true}).click();
 await expect(page.locator('.rpt-metric').first()).toContainText('Unavailable');
 await expect(page.locator('.rpt-metrics')).not.toContainText('94.3');
 pass('Changing a sample input removes recorded outputs');
 await page.getByRole('button',{name:'Edit inputs',exact:true}).click();
 await page.getByLabel('Select ECG waveform').setInputFiles('qa/fixtures/recorded-waveform.csv');
 await expect(page.getByText(/12-lead waveform loaded/)).toBeVisible();
 await page.locator('.inp-footer button').click();
 await page.getByRole('button',{name:'View report',exact:true}).click();
 await page.getByRole('tab',{name:'ECG explorer',exact:true}).click();
 await page.getByLabel('Lead',{exact:true}).selectOption('II');
 await page.getByLabel('Zoom',{exact:true}).selectOption('4');
 await expect(page.getByLabel('Position in recording')).toBeVisible();
 await expect(page.locator('.rpt-wave-chart svg')).toHaveAttribute('aria-label',/lead II/);
 await page.getByLabel('Position in recording').fill('100');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 pass('Actual 12-lead CSV supports lead selection, zoom, and pan');
 await page.screenshot({path:'qa/screenshots/waveform-mobile.png',fullPage:true});
 await page.emulateMedia({reducedMotion:'reduce'});
 expect(await page.locator('.rpt-tab-panel:visible').evaluate(e=>getComputedStyle(e).animationName)).toBe('none');
 expect(errors).toEqual([]);expect(requests).toEqual([]);
 pass('Reduced motion respected; no API/remote calls or runtime errors');
 await writeFile('qa/report-results.json',JSON.stringify({checks,requests,errors},null,2));
}catch(e){await page.screenshot({path:'qa/screenshots/report-failure.png',fullPage:true});throw e;}finally{await browser.close()}

